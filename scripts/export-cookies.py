#!/usr/bin/env python3
"""Export YouTube cookies from Firefox to Netscape format.

Runs on the desktop that has Firefox; the server has no browser and only
receives the resulting cookies.txt via push-cookies.bat.

YouTube ST-* cookies accumulate in Firefox and can inflate the Cookie header
enough to cause HTTP 413 errors. They are excluded; login cookies are retained.

Usage:
    python export-cookies.py                    # writes to ./cookies.txt
    python export-cookies.py -o /path/out.txt  # custom output
"""

import argparse
import sys
import tempfile
from pathlib import Path

try:
    import browser_cookie3
except ImportError:
    print("ERROR: browser-cookie3 not installed. Run: pip install browser-cookie3", file=sys.stderr)
    sys.exit(1)


def export_cookies(output_path: Path) -> int:
    """Extract Firefox cookies for YouTube and write Netscape format.

    Returns the number of cookies written. Writes nothing when Firefox has no
    YouTube cookies, so a transient logout cannot wipe a working cookies.txt.
    """
    try:
        cj = browser_cookie3.firefox(domain_name="youtube.com")
    except browser_cookie3.BrowserCookieError as e:
        print(f"ERROR: Could not read Firefox cookies: {e}", file=sys.stderr)
        print("       Is Firefox installed? Run it once to create the profile.", file=sys.stderr)
        return 0
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 0

    # browser_cookie3 matches the domain as a substring; keep exact suffixes
    # so cookies from look-alike domains (e.g. notyoutube.com) never leak out.
    # ST-* cookies accumulate across browsing sessions (126 KB on one profile),
    # making even a simple search fail with HTTP 413. Do not export them; keep
    # the authentication and preference cookies rather than truncating values.
    cookies = [
        c for c in cj
        if (c.domain == "youtube.com" or c.domain.endswith(".youtube.com"))
        and not c.name.startswith("ST-")
    ]
    if not cookies:
        print("ERROR: No usable YouTube cookies found in Firefox. Log in to YouTube and retry.", file=sys.stderr)
        return 0

    lines = ["# Netscape HTTP Cookie File", "# Generated by export-cookies.py"]
    for c in cookies:
        # Column 2 is "include subdomains", not HttpOnly.
        subdomains = "TRUE" if c.domain.startswith(".") else "FALSE"
        secure = "TRUE" if c.secure else "FALSE"
        expires = str(int(c.expires)) if c.expires else "0"
        lines.append("\t".join([
            c.domain,
            subdomains,
            c.path,
            secure,
            expires,
            c.name,
            c.value,
        ]))

    # Write next to the destination so replacement is atomic (also on Windows).
    # A failed export must not truncate the previous working credentials.
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=output_path.parent,
            prefix=f".{output_path.name}.", suffix=".tmp", delete=False,
        ) as temporary:
            temporary_path = Path(temporary.name)
            temporary.write("\n".join(lines) + "\n")
        temporary_path.replace(output_path)
    except OSError as e:
        print(f"ERROR: Could not write cookies: {e}", file=sys.stderr)
        return 0
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()
    print(f"Wrote {len(cookies)} cookies to {output_path}")
    return len(cookies)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Export Firefox YouTube cookies")
    ap.add_argument("-o", "--output", default="cookies.txt", help="Output file (default: cookies.txt)")
    args = ap.parse_args()
    sys.exit(0 if export_cookies(Path(args.output)) else 1)
