#!/usr/bin/env python3
"""
Export YouTube cookies from Firefox to Netscape format.

Usage:
    python export-cookies.py                    # writes to ./cookies.txt
    python export-cookies.py -o /path/out.txt  # custom output
    python export-cookies.py --domain youtube.com  # specific domain
"""

import argparse
import sys
from pathlib import Path

try:
    import browser_cookie3
except ImportError:
    print("ERROR: browser-cookie3 not installed. Run: pip install browser-cookie3", file=sys.stderr)
    sys.exit(1)

# youtu.be is also needed for embedded players
YT_DOMAINS = (".youtube.com", "youtube.com", ".youtu.be", "youtu.be")

def export_cookies(output_path: Path, domains=YT_DOMAINS):
    """Extract Firefox cookies for YouTube and write Netscape format."""
    try:
        cj = browser_cookie3.firefox(domain_name="youtube.com")
    except browser_cookie3.BrowserCookieError as e:
        print(f"ERROR: Could not read Firefox cookies: {e}", file=sys.stderr)
        print("       Is Firefox installed? Run it once to create the profile.", file=sys.stderr)
        sys.exit(1)
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    # Filter for YouTube domains (browser_cookie3 domain_name is a prefix match)
    cookies = [c for c in cj if any(c.domain.endswith(d.lstrip(".")) for d in domains)]
    if not cookies:
        print("WARNING: No YouTube cookies found in Firefox. Are you logged in?", file=sys.stderr)

    # Netscape format
    lines = ["# Netscape HTTP Cookie File", "# Generated by export-cookies.py"]
    for c in cookies:
        # browser_cookie3 gives: name, value, domain, path, secure, expires, http_only
        domain = c.domain
        # Ensure leading dot for Netscape (all subdomains)
        if not domain.startswith("."):
            domain = "." + domain
        secure = "TRUE" if c.secure else "FALSE"
        http_only = "TRUE" if getattr(c, "http_only", False) else "FALSE"
        expires = str(int(c.expires)) if c.expires else "0"
        lines.append("\t".join([
            domain,
            http_only,      # HTTP only flag (Netscape uses this column for tail-match)
            c.path,
            secure,
            expires,
            c.name,
            c.value,
        ]))

    output_path.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"Wrote {len(cookies)} cookies to {output_path}")
    return len(cookies)

if __name__ == "__main__":
    ap = argparse.ArgumentParser(description="Export Firefox YouTube cookies")
    ap.add_argument("-o", "--output", default="cookies.txt", help="Output file (default: cookies.txt)")
    ap.add_argument("--domain", default="youtube.com", help="Cookie domain (default: youtube.com)")
    args = ap.parse_args()

    export_cookies(Path(args.output))